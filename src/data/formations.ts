const makeFormation = (
  id: FormationId,
  description: string,
  slots: FormationSlot[],
  managerStyles: ManagerStyle[],
  eraStrengths: DraftEraId[],
  tendencies: Formation["tendencies"],
  width: number,
  pressingSuitability: number,
  tacticalDifficulty: Formation["tacticalDifficulty"],
  preferredArchetypes: string[],
): Formation => ({
  id,
  name: id.replaceAll("-", "–"),
  description,
  slots,
  managerStyles,
  eraStrengths,
  tendencies,
  modifiers: {
    attack: Math.round((tendencies.attack - 80) / 5),
    midfield: Math.round((tendencies.control - 80) / 5),
    defense: Math.round((tendencies.defense - 80) / 5),
  },
  width,
  pressingSuitability,
  tacticalDifficulty,
  preferredArchetypes,
});

